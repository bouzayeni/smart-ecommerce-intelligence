"""Bronze layer: load raw Olist CSVs into PostgreSQL unmodified, with ingestion metadata.

Every source column is stored as TEXT exactly as it appears in the file (unquoted empty
fields become NULL, as in PostgreSQL CSV COPY). Each table is replaced atomically: the file
is streamed with COPY into a temporary table, then swapped in with TRUNCATE + INSERT inside
one transaction, so a failed load leaves the previous version in place.

Re-running is idempotent: a table whose last successful load came from a file with the same
SHA-256 is skipped unless forced. Every attempt is recorded in <schema>._ingestion_log.
"""

import json
import logging
import time
import uuid
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Literal

import psycopg
from psycopg import sql

from data_engineering.business_rules import BusinessRules
from data_engineering.quality.checks import run_checks
from data_engineering.quality.loader import load_raw
from data_engineering.scripts.download_dataset import MANIFEST_NAME, sha256_of
from data_engineering.sources import SOURCE_FILES, SourceFile
from data_engineering.validation.contracts import validate_file

log = logging.getLogger(__name__)

META_COLUMNS: tuple[tuple[str, str], ...] = (
    ("_batch_id", "uuid NOT NULL"),
    ("_source_file", "text NOT NULL"),
    ("_source_sha256", "char(64) NOT NULL"),
    ("_source_row", "bigint NOT NULL"),  # 1-based data row number in the source file
    ("_ingested_at", "timestamptz NOT NULL"),
)
LOG_TABLE = "_ingestion_log"


class BronzeError(RuntimeError):
    pass


@dataclass(frozen=True)
class TableResult:
    table: str
    status: Literal["loaded", "skipped", "failed"]
    rows: int
    seconds: float
    message: str = ""


def render_ddl(schema: str = "raw") -> str:
    """DDL for the bronze schema; committed as warehouse/sql/bronze/001_raw_tables.sql."""
    lines = [
        "-- Bronze layer DDL. Generated by:",
        "--   uv run python -m data_engineering.etl.load_bronze --print-ddl",
        "-- Do not edit by hand; change data_engineering/sources.py and regenerate.",
        "",
        f"CREATE SCHEMA IF NOT EXISTS {schema};",
        "",
        f"CREATE TABLE IF NOT EXISTS {schema}.{LOG_TABLE} (",
        "    log_id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,",
        "    batch_id      uuid NOT NULL,",
        "    table_name    text NOT NULL,",
        "    source_file   text NOT NULL,",
        "    source_sha256 char(64),",
        "    status        text NOT NULL CHECK (status IN ('loaded', 'skipped', 'failed')),",
        "    rows_loaded   bigint,",
        "    started_at    timestamptz NOT NULL,",
        "    finished_at   timestamptz NOT NULL,",
        "    message       text",
        ");",
        f"CREATE INDEX IF NOT EXISTS {LOG_TABLE}_table_idx",
        f"    ON {schema}.{LOG_TABLE} (table_name, status, finished_at DESC);",
    ]
    for spec in SOURCE_FILES:
        cols = [f"    {c} text" for c in spec.columns]
        cols += [f"    {name} {ddl}" for name, ddl in META_COLUMNS]
        lines += [
            "",
            f"-- {spec.filename}",
            f"CREATE TABLE IF NOT EXISTS {schema}.{spec.table} (",
            ",\n".join(cols),
            ");",
        ]
    return "\n".join(lines) + "\n"


def verify_manifest(raw_dir: Path) -> dict[str, str]:
    """Return {filename: sha256} for present source files, checked against the manifest."""
    manifest_path = raw_dir / MANIFEST_NAME
    if not manifest_path.is_file():
        raise BronzeError(f"No {MANIFEST_NAME} in {raw_dir}; run download_dataset first")
    expected = json.loads(manifest_path.read_text(encoding="utf-8"))["files"]
    hashes = {}
    for spec in SOURCE_FILES:
        path = raw_dir / spec.filename
        if not path.is_file():
            continue
        actual = sha256_of(path)
        if spec.filename not in expected or expected[spec.filename]["sha256"] != actual:
            raise BronzeError(f"{spec.filename} does not match {MANIFEST_NAME}: file changed")
        hashes[spec.filename] = actual
    return hashes


def preflight(raw_dir: Path, rules: BusinessRules, *, verify: bool = True) -> dict[str, str]:
    """All gates that must pass before anything is written. Returns file hashes."""
    present = [s for s in SOURCE_FILES if (raw_dir / s.filename).is_file()]
    missing_required = [s.filename for s in SOURCE_FILES if s.required and s not in present]
    if missing_required:
        raise BronzeError(f"Required file(s) missing: {', '.join(missing_required)}")
    for spec in SOURCE_FILES:
        if spec not in present:
            log.warning("Optional file missing, table %s will not be loaded", spec.table)

    hashes = (
        verify_manifest(raw_dir)
        if verify
        else {s.filename: sha256_of(raw_dir / s.filename) for s in present}
    )
    for spec in present:
        rows = validate_file(spec, raw_dir / spec.filename)  # raises ContractError
        log.info("Contract OK  %-22s %9d rows", spec.table, rows)

    failed = [
        r for r in run_checks(load_raw(raw_dir), rules) if r.severity == "error" and not r.passed
    ]
    if failed:
        details = "; ".join(f"{r.check_id} ({r.failed} rows)" for r in failed)
        raise BronzeError(f"Quality gate failed: {details}")
    log.info("Quality gate OK (all error-level checks pass)")
    return hashes


def _ensure_schema(conn: psycopg.Connection, schema: str) -> None:
    with conn.transaction():
        conn.execute(render_ddl(schema))
        for spec in SOURCE_FILES:
            actual = [
                row[0]
                for row in conn.execute(
                    "SELECT column_name FROM information_schema.columns "
                    "WHERE table_schema = %s AND table_name = %s ORDER BY ordinal_position",
                    (schema, spec.table),
                )
            ]
            expected = list(spec.columns) + [name for name, _ in META_COLUMNS]
            if actual != expected:
                raise BronzeError(
                    f"{schema}.{spec.table} columns differ from the contract (schema drift); "
                    f"expected {expected}, found {actual}"
                )


def _last_loaded_sha(conn: psycopg.Connection, schema: str, table: str) -> str | None:
    row = conn.execute(
        sql.SQL(
            "SELECT source_sha256 FROM {} WHERE table_name = %s AND status = 'loaded' "
            "ORDER BY finished_at DESC, log_id DESC LIMIT 1"
        ).format(sql.Identifier(schema, LOG_TABLE)),
        (table,),
    ).fetchone()
    return row[0] if row else None


def _log(conn, schema, batch_id, spec, sha, status, rows, started, message="") -> None:
    conn.execute(
        sql.SQL(
            "INSERT INTO {} (batch_id, table_name, source_file, source_sha256, status, "
            "rows_loaded, started_at, finished_at, message) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s, now(), %s)"
        ).format(sql.Identifier(schema, LOG_TABLE)),
        (batch_id, spec.table, spec.filename, sha, status, rows, started, message or None),
    )


def _load_table(
    conn: psycopg.Connection, schema: str, spec: SourceFile, path: Path, sha: str,
    batch_id: uuid.UUID, ingested_at: datetime,
) -> int:  # fmt: skip
    cols = sql.SQL(", ").join(sql.Identifier(c) for c in spec.columns)
    stage_cols = sql.SQL(", ").join(
        sql.SQL("{} text").format(sql.Identifier(c)) for c in spec.columns
    )
    target = sql.Identifier(schema, spec.table)
    meta = sql.SQL(", ").join(sql.Identifier(name) for name, _ in META_COLUMNS)
    with conn.transaction():
        conn.execute(
            sql.SQL(
                "CREATE TEMP TABLE _bronze_stage "
                "(_source_row bigint GENERATED ALWAYS AS IDENTITY, {}) ON COMMIT DROP"
            ).format(stage_cols)
        )
        with conn.cursor() as cur:
            copy_sql = sql.SQL(
                "COPY _bronze_stage ({}) FROM STDIN WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')"
            ).format(cols)
            with cur.copy(copy_sql) as copy, path.open("rb") as fh:
                while chunk := fh.read(1 << 20):
                    copy.write(chunk)
        conn.execute(sql.SQL("TRUNCATE {}").format(target))
        inserted = conn.execute(
            sql.SQL(
                "INSERT INTO {target} ({cols}, {meta}) "
                "SELECT {cols}, %s, %s, %s, _source_row, %s FROM _bronze_stage "
                "ORDER BY _source_row"
            ).format(target=target, cols=cols, meta=meta),
            (batch_id, spec.filename, sha, ingested_at),
        ).rowcount
        _log(conn, schema, batch_id, spec, sha, "loaded", inserted, ingested_at)
    return inserted


def run_bronze(
    conn: psycopg.Connection, raw_dir: Path, rules: BusinessRules, *, schema: str = "raw",
    force: bool = False, verify_manifest_hashes: bool = True,
) -> list[TableResult]:  # fmt: skip
    """Run preflight gates, then load every present source file into `schema`."""
    hashes = preflight(raw_dir, rules, verify=verify_manifest_hashes)
    _ensure_schema(conn, schema)
    batch_id = uuid.uuid4()
    log.info("Batch %s -> schema %s", batch_id, schema)

    results = []
    for spec in SOURCE_FILES:
        path = raw_dir / spec.filename
        if not path.is_file():
            continue
        sha, started, t0 = hashes[spec.filename], datetime.now(UTC), time.perf_counter()
        if not force and _last_loaded_sha(conn, schema, spec.table) == sha:
            with conn.transaction():
                _log(conn, schema, batch_id, spec, sha, "skipped", 0, started, "unchanged hash")
            results.append(TableResult(spec.table, "skipped", 0, time.perf_counter() - t0))
            log.info("Skipped      %-22s (unchanged since last load)", spec.table)
            continue
        try:
            rows = _load_table(conn, schema, spec, path, sha, batch_id, started)
        except psycopg.Error as exc:
            with conn.transaction():
                _log(conn, schema, batch_id, spec, sha, "failed", None, started, str(exc))
            results.append(TableResult(spec.table, "failed", 0, time.perf_counter() - t0, str(exc)))
            log.error("Failed       %-22s %s", spec.table, exc)
            continue
        results.append(TableResult(spec.table, "loaded", rows, time.perf_counter() - t0))
        log.info("Loaded       %-22s %9d rows %6.1fs", spec.table, rows, time.perf_counter() - t0)
    return results
