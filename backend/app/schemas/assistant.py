from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class HistoryTurn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=8000)


class AssistantQuery(BaseModel):
    model_config = ConfigDict(extra="forbid")

    question: str = Field(min_length=1, max_length=1000)
    # Earlier turns (text only) for follow-up questions; tool results are not replayed.
    history: list[HistoryTurn] = Field(default_factory=list, max_length=10)

    @model_validator(mode="after")
    def alternating(self):
        expected = "user"
        for turn in self.history:
            if turn.role != expected:
                raise ValueError("history must alternate user/assistant, starting with user")
            expected = "assistant" if expected == "user" else "user"
        if self.history and self.history[-1].role != "assistant":
            raise ValueError("history must end with an assistant turn")
        self.question = self.question.strip()
        if not self.question:
            raise ValueError("question must not be blank")
        return self


class ToolCallOut(BaseModel):
    name: str
    input: dict
    status: Literal["ok", "error"]
    meta: dict | None = None
    error: str | None = None
    data: dict | list | None = None
    ms: int


class AssistantAnswer(BaseModel):
    status: str
    answer: str
    model: str | None
    served_by_fallback: bool
    tool_calls: list[ToolCallOut]
    iterations: int
    usage: dict
    latency_ms: int
    disclaimer: str = (
        "Answers are generated by an AI model from the tool results listed under tool_calls. "
        "Check the figures there; historical Olist data (2016-2018), not live business data."
    )
