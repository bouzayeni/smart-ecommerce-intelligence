import { useState, type FormEvent } from "react";

import { Async, Badge, Button, Card, ErrorState, PageHeader } from "../components/ui";
import { useApi } from "../hooks/useApi";
import { num } from "../lib/format";
import { api, toFailure, type ApiFailure } from "../services/api";
import type { AssistantAnswer, AssistantStatus, AssistantTool, AssistantToolCall } from "../types/api";

interface Turn {
  question: string;
  answer?: AssistantAnswer;
  error?: ApiFailure;
}

const STATUS_LABEL: Record<AssistantAnswer["status"], { label: string; tone: "good" | "warning" | "critical" }> = {
  answered: { label: "Answered", tone: "good" },
  refused: { label: "Declined by the model", tone: "warning" },
  iteration_limit: { label: "Stopped at tool-call limit", tone: "warning" },
  truncated: { label: "Answer truncated", tone: "warning" },
  error: { label: "Error", tone: "critical" },
};
const MAX_HISTORY_PAIRS = 5; // the API accepts at most 10 history turns

/**
 * Chat over the assistant API. Answers are rendered as plain text (never HTML) and each one lists
 * the tool calls, with metric, window, filters and row counts, that its figures came from.
 */
export default function AssistantPage() {
  const status = useApi<AssistantStatus>("/assistant/status");

  return (
    <>
      <PageHeader title="AI business assistant"
        description="Ask questions about the warehouse in plain language. The model can only call read-only analytics tools; every answer lists the data it used." />
      <Async state={status}>
        {(s) => (s.llm_enabled ? <Chat status={s} /> : <ToolsOnly />)}
      </Async>
    </>
  );
}

function Chat({ status }: { status: AssistantStatus }) {
  const [turns, setTurns] = useState<Turn[]>([]);
  const [question, setQuestion] = useState("");
  const [pending, setPending] = useState(false);

  async function ask(q: string) {
    const text = q.trim();
    if (!text || pending) return;
    // Text-only history of completed exchanges, so follow-up questions have context.
    const history = turns
      .filter((t) => t.answer?.status === "answered")
      .slice(-MAX_HISTORY_PAIRS)
      .flatMap((t) => [
        { role: "user", content: t.question },
        { role: "assistant", content: t.answer!.answer },
      ]);
    setTurns((ts) => [...ts, { question: text }]);
    setQuestion("");
    setPending(true);
    try {
      const { data } = await api.post<AssistantAnswer>("/assistant/query", { question: text, history }, { timeout: 180_000 });
      setTurns((ts) => ts.map((t, i) => (i === ts.length - 1 ? { ...t, answer: data } : t)));
    } catch (e) {
      setTurns((ts) => ts.map((t, i) => (i === ts.length - 1 ? { ...t, error: toFailure(e) } : t)));
    } finally {
      setPending(false);
    }
  }

  function submit(e: FormEvent) {
    e.preventDefault();
    void ask(question);
  }

  return (
    <div className="space-y-4">
      <Card>
        <p className="text-xs text-muted">
          Model <code>{status.model}</code> · effort {status.effort} · up to {status.max_iterations} tool rounds per question.
          Answers are generated by an AI model and can be wrong: check the figures under "Data used". Historical Olist data
          (2016–2018), not live business data.
        </p>
        {turns.length === 0 && (
          <div className="mt-4 flex flex-wrap gap-2">
            {status.example_questions.map((q) => (
              <Button key={q} variant="secondary" className="text-xs" onClick={() => void ask(q)} disabled={pending}>{q}</Button>
            ))}
          </div>
        )}
      </Card>

      <ol className="space-y-4" aria-live="polite">
        {turns.map((t, i) => (
          <li key={i} className="space-y-2">
            <div className="ml-auto max-w-2xl rounded-xl bg-accent-soft px-4 py-3 text-sm text-text">{t.question}</div>
            {t.answer ? <AnswerCard answer={t.answer} /> : t.error ? <ErrorState error={t.error} /> : (
              <Card><p role="status" className="text-sm text-text-2">Looking up the data… this can take up to a minute.</p></Card>
            )}
          </li>
        ))}
      </ol>

      <form onSubmit={submit} className="flex gap-2">
        <label htmlFor="assistant-question" className="sr-only">Question</label>
        <textarea id="assistant-question" value={question} maxLength={1000} rows={2}
          onChange={(e) => setQuestion(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && !e.shiftKey) {
              e.preventDefault();
              void ask(question);
            }
          }}
          placeholder="e.g. Which states had the most late deliveries in 2018?"
          className="w-full resize-y rounded-lg border border-border bg-surface px-3 py-2 text-sm text-text placeholder:text-muted focus:border-accent focus:outline-none" />
        <Button type="submit" disabled={pending || !question.trim()}>{pending ? "Asking…" : "Ask"}</Button>
      </form>
    </div>
  );
}

function AnswerCard({ answer }: { answer: AssistantAnswer }) {
  const s = STATUS_LABEL[answer.status];
  return (
    <Card>
      <div className="mb-3 flex flex-wrap items-center gap-2">
        <Badge tone={s.tone}>{s.label}</Badge>
        {answer.served_by_fallback && <Badge tone="warning">Served by fallback model</Badge>}
        <span className="text-xs text-muted">
          {(answer.latency_ms / 1000).toFixed(1)} s · {num(answer.usage.input_tokens)} in / {num(answer.usage.output_tokens)} out tokens
        </span>
      </div>
      {/* Plain text only: model output is never interpreted as HTML or Markdown. */}
      <p className="whitespace-pre-wrap text-sm leading-6 text-text">{answer.answer}</p>
      <details className="mt-4 rounded-lg border border-border p-3">
        <summary className="cursor-pointer text-xs font-medium text-text-2">
          Data used ({answer.tool_calls.length} tool call{answer.tool_calls.length === 1 ? "" : "s"})
        </summary>
        {answer.tool_calls.length === 0 ? (
          <p className="mt-2 text-xs text-muted">No tools were called; the answer does not contain warehouse figures.</p>
        ) : (
          <ul className="mt-2 space-y-3">{answer.tool_calls.map((c, i) => <ToolCallItem key={i} call={c} />)}</ul>
        )}
      </details>
    </Card>
  );
}

function ToolCallItem({ call }: { call: AssistantToolCall }) {
  const filters = Object.entries(call.meta?.filters ?? {});
  return (
    <li className="text-xs">
      <div className="flex flex-wrap items-center gap-2">
        <code className="font-medium text-text">{call.name}</code>
        <Badge tone={call.status === "ok" ? "good" : "critical"}>{call.status}</Badge>
        <span className="text-muted">{call.ms} ms</span>
      </div>
      {call.error && <p className="mt-1 text-critical">{call.error}</p>}
      {call.meta && (
        <dl className="mt-1 grid gap-x-3 gap-y-0.5 text-text-2 sm:grid-cols-[auto_1fr]">
          <dt className="text-muted">Metric</dt><dd>{call.meta.metric}</dd>
          <dt className="text-muted">Window</dt><dd>{call.meta.window}</dd>
          <dt className="text-muted">Source</dt><dd><code>{call.meta.source}</code></dd>
          <dt className="text-muted">Filters</dt>
          <dd className="break-all">{filters.length ? filters.map(([k, v]) => `${k}=${String(v)}`).join(", ") : "none"}</dd>
          <dt className="text-muted">Rows</dt><dd>{call.meta.rows}</dd>
        </dl>
      )}
    </li>
  );
}

/** Without an LLM key: the same validated tools, run directly with JSON arguments. */
function ToolsOnly() {
  const tools = useApi<{ items: AssistantTool[] }>("/assistant/tools");
  return (
    <div className="space-y-4">
      <Card>
        <p className="text-sm text-text">The AI assistant is not configured on this server (no LLM API key).</p>
        <p className="mt-1 text-sm text-text-2">
          You can still run the analytics tools the assistant would use. Results come straight from the warehouse;
          nothing is generated.
        </p>
      </Card>
      <Async state={tools}>
        {(t) => <div className="grid gap-4 xl:grid-cols-2">{t.items.map((tool) => <ToolRunner key={tool.name} tool={tool} />)}</div>}
      </Async>
    </div>
  );
}

function ToolRunner({ tool }: { tool: AssistantTool }) {
  const [args, setArgs] = useState("{}");
  const [result, setResult] = useState<unknown>(null);
  const [error, setError] = useState<ApiFailure | null>(null);
  const [pending, setPending] = useState(false);
  const params = Object.keys(tool.input_schema.properties ?? {});

  async function run() {
    setError(null);
    setResult(null);
    let parsed: unknown;
    try {
      parsed = JSON.parse(args);
    } catch {
      setError({ status: null, code: "invalid_json", message: "Arguments must be valid JSON.", requestId: null });
      return;
    }
    setPending(true);
    try {
      setResult((await api.post(`/assistant/tools/${tool.name}`, parsed)).data);
    } catch (e) {
      setError(toFailure(e));
    } finally {
      setPending(false);
    }
  }

  return (
    <Card title={<code>{tool.name}</code>} subtitle={tool.description}
      actions={tool.min_role !== "viewer" ? <Badge tone="accent">{tool.min_role}</Badge> : undefined}>
      {params.length > 0 && <p className="mb-2 text-xs text-muted">Arguments: {params.join(", ")}</p>}
      <div className="flex gap-2">
        <label htmlFor={`args-${tool.name}`} className="sr-only">Arguments (JSON)</label>
        <input id={`args-${tool.name}`} value={args} onChange={(e) => setArgs(e.target.value)} spellCheck={false}
          className="w-full rounded-lg border border-border bg-surface px-3 py-2 font-mono text-xs text-text focus:border-accent focus:outline-none" />
        <Button variant="secondary" onClick={() => void run()} disabled={pending}>{pending ? "Running…" : "Run"}</Button>
      </div>
      {error && <div className="mt-3"><ErrorState error={error} /></div>}
      {result != null && (
        <pre className="mt-3 max-h-80 overflow-auto rounded-lg bg-surface-2 p-3 text-xs text-text-2">{JSON.stringify(result, null, 2)}</pre>
      )}
    </Card>
  );
}
